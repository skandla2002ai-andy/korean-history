def make_era_tags(eras):
    tags = []
    for e in eras:
        url = ERA_URLS.get(e, e)
        tags.append(f'    <a class="tag" href="/korean-history/era/{url}.html"><b>시대</b> {e}</a>')
    return "\n".join(tags)


def make_topic_tags(topics):
    tags = []
    for t in topics:
        url = TOPIC_URLS.get(t, t)
        tags.append(f'    <a class="tag" href="/korean-history/topics/{url}.html"><b>주제</b> {t}</a>')
    return "\n".join(tags)


def make_related_tags(related):
    tags = []
    for r in related:
        url = RELATED_URLS.get(r)
        if url:
            tags.append(f'    <a class="tag" href="/korean-history/related/{url}.html"><b>관련국</b> {r}</a>')
    return "\n".join(tags)


def make_region_tags(regions):
    tags = []
    for r in regions:
        url = REGION_URLS.get(r)
        if url:
            tags.append(f'    <a class="tag" href="/korean-history/region/{url}.html"><b>지역</b> {r}</a>')
    return "\n".join(tags)


